const STORAGE_FONT_KEY = 'panda_selected_font_id';

export function getAvailableFonts(): FontOption[] {
  return AVAILABLE_FONTS;
}

export function getFontById(id?: string): FontOption {
  if (!id) return AVAILABLE_FONTS[0]; // Baloo as the premier featured font or matching selection
  return AVAILABLE_FONTS.find(f => f.id === id) || AVAILABLE_FONTS[0];
}

export function getStoredFontId(): string {
  try {
    const stored = localStorage.getItem(STORAGE_FONT_KEY);
    if (stored && AVAILABLE_FONTS.some(f => f.id === stored)) {
      return stored;
    }
  } catch {}
  return 'baloo'; // Default to Baloo (Image 1) or user choice
}

export function saveStoredFontId(id: string): void {
  try {
    localStorage.setItem(STORAGE_FONT_KEY, id);
  } catch {}
}

export function applyFontToDocument(fontId: string): FontOption {
  const font = getFontById(fontId);
  try {
    // 1. Update CSS custom variable on root
    document.documentElement.style.setProperty('--app-font-family', font.fontFamily);
    
    // 2. Direct style injection to guarantee immediate global application
    let styleTag = document.getElementById('panda-dynamic-font-override') as HTMLStyleElement | null;
    if (!styleTag) {
      styleTag = document.createElement('style');
      styleTag.id = 'panda-dynamic-font-override';
      document.head.appendChild(styleTag);
    }

    styleTag.textContent = `
      :root {
        --app-font-family: ${font.fontFamily} !important;
      }
      body, 
      #root, 
      button, 
      input, 
      select, 
      textarea, 
      h1, h2, h3, h4, h5, h6, 
      p, span, div, a, label {
        font-family: var(--app-font-family) !important;
      }
    `;

    // 3. Save preference
    saveStoredFontId(font.id);
  } catch (err) {
    console.error('Failed to apply font to document:', err);
  }
  return font;
}
